#!/usr/bin/env python3
"""Skeleton for generating a C++ Motif header from a mir JSON artifact."""

import argparse
from graphlib import CycleError, TopologicalSorter
import json
import re
from pathlib import Path


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "input",
        nargs="?",
        type=Path,
        default=Path("mir.json"),
        help="input artifact path (default: mir.json)",
    )
    parser.add_argument(
        "-o",
        "--output",
        type=Path,
        default=Path("cmotif_impl.h"),
        help="output C++ header path (default: cmotif_impl.h)",
    )
    return parser, parser.parse_args(argv)


def generate_header(artifact):
    """Generate widget classes with each superclass before its subclasses."""
    widgets = artifact["widgets"]
    symbols = {}
    headers = {}
    parents = {}
    resources = {}
    for symbol in sorted(widgets):
        widget = widgets[symbol]
        name = widget["name"]
        symbols.setdefault(name, symbol)
        headers.setdefault(name, widget["header"])
        superclass = widgets.get(widget.get("superclass"))
        parent = superclass["name"] if superclass is not None else None
        # Multiple WidgetClass symbols can name the same C++ class.
        parents.setdefault(name, parent)
        resources.setdefault(name, widget.get("resources", {}))

    hierarchy = TopologicalSorter(
        {
            name: (parent,) if parent is not None else ()
            for name, parent in parents.items()
        }
    )
    blocks = ["// Generated by mkcpp.py.\n#pragma once"]
    for name in hierarchy.static_order():
        superclass = (
            "C" + parents[name] if parents[name] is not None else "CWidget"
        )
        accessors = []
        for resource_name, resource in sorted(resources[name].items()):
            ctype = resource.get("ctype")
            if ctype is None:
                continue
            method_name = re.sub(r"[^a-zA-Z0-9_]", "_", resource_name)
            method_name = method_name[:1].upper() + method_name[1:]
            # Array dimensions belong after the parameter name in C++.
            array = re.fullmatch(r"(.+?)\s*((?:\[[^\]]*\]\s*)+)", ctype)
            parameter = (
                f"{array[1]} value{array[2]}" if array else f"{ctype} value"
            )
            accessors.append(
                f"""    Derived& set{method_name}({parameter}) {{
        XtVaSetValues(this->_widget, {json.dumps(resource_name)}, value, nullptr);
        return static_cast<Derived&>(*this);
    }}"""
            )

        setters = "\n".join(accessors)
        blocks.append(
            f"""
template <typename Derived> class C{name}Impl : public {superclass}Impl<Derived> {{
public:
    using {superclass}Impl<Derived>::{superclass}Impl;
{setters}
}};
class C{name} : public C{name}Impl<C{name}> {{
public:
    using C{name}Impl<C{name}>::C{name}Impl;
    static C{name} create(Widget parent, const char* name) {{
        return C{name}(XtCreateWidget(name, {symbols[name]}, parent, nullptr, 0));
    }}
}};
"""
        )
    return "\n\n".join(blocks) + "\n"


def main(argv=None):
    parser, args = parse_args(argv)
    try:
        artifact = json.loads(args.input.read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        parser.error(f"could not read input: {exc}")

    try:
        args.output.write_text(generate_header(artifact), encoding="utf-8")
    except CycleError as exc:
        parser.error(f"cyclic widget hierarchy: {exc}")
    except OSError as exc:
        parser.error(f"could not write output: {exc}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
